import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { muscleCatalog, resolveMuscleReference, accountingMuscle, muscleCatalogContext } from "../lib/muscles/catalog";
import { exerciseMechanicsSchemaForCatalog, reconcileMechanicsTargets, readMechanics, mechanicsBasis, summarizeExerciseMechanics } from "../lib/coaching/exercise-mechanics";
import { visualAssessmentSchemaForCatalog } from "../lib/physique/policy";
import { fixtureProfile } from "./test-exercise-mechanics";
const muscles = muscleCatalog.map((m,i) => ({ ...m, id: `11111111-1111-4111-8111-${String(i+1).padStart(12,'0')}` }));
assert.equal(new Set(muscles.map(m=>m.slug)).size,muscles.length);
assert.equal(new Set(muscles.map(m=>m.name)).size,muscles.length);
for (const m of muscles) {
 const group = accountingMuscle(m,muscles); assert.ok(group, m.name); assert.equal(group.accountingSlug,null);
 assert.equal(resolveMuscleReference(m.name,muscles)?.id,m.id);
 for (const alias of m.aliases) assert.equal(resolveMuscleReference(alias,muscles)?.id,m.id,`Unambiguous alias: ${alias}`);
}
for (const slug of ['soleus','rectus-femoris','teres-major','supraspinatus','tibialis-anterior','hip-adductors','diaphragm','pelvic-floor','masseter','intrinsic-hand-muscles','intrinsic-foot-muscles']) assert.ok(muscles.some(m=>m.slug===slug));
assert.equal(resolveMuscleReference('  REAR-DELT ',muscles)?.slug,'rear-delts');
assert.equal(resolveMuscleReference('rhomboids',muscles)?.slug,'rhomboids');
assert.equal(resolveMuscleReference('inner chest',muscles),null);
const soleus=muscles.find(m=>m.slug==='soleus')!, calves=muscles.find(m=>m.slug==='calves')!;
assert.equal(accountingMuscle(soleus,muscles)?.id,calves.id);
const schema=exerciseMechanicsSchemaForCatalog(muscles.map(m=>m.id));
const profile={...fixtureProfile,targets:[{...fixtureProfile.targets[0],muscleId:soleus.id,muscleName:soleus.name,contributionEstimate:null}]};
assert.ok(schema.safeParse(profile).success);
assert.ok(!schema.safeParse({...profile,targets:[{...profile.targets[0],muscleId:'99999999-9999-4999-8999-999999999999'}]}).success);
const unknown=reconcileMechanicsTargets({...profile,targets:[{...profile.targets[0],muscleId:null,muscleName:'Unlisted anatomy'}]},muscles);
assert.equal(unknown.targets[0].muscleName,'Unlisted anatomy');assert.equal(unknown.targets[0].muscleId,null);
assert.ok(schema.safeParse(unknown).success);
const repaired=reconcileMechanicsTargets({...profile,targets:[{...profile.targets[0],muscleId:null,muscleName:'peroneus longus'}]},muscles);
assert.equal(repaired.targets[0].muscleId,muscles.find(m=>m.slug==='fibularis-longus')!.id);
const conflict=reconcileMechanicsTargets({...profile,targets:[{...profile.targets[0],muscleName:'Biceps'}]},muscles);
assert.equal(conflict.targets[0].muscleId,null,'A valid ID conflicting with a known label needs review');
const exercise={name:'Existing exercise',movementGroupId:'old',primaryMuscles:[{muscleId:calves.id}],secondaryMuscles:[]};
const basis=mechanicsBasis(exercise,null);
const envelope={version:1,source:'VIDEO_FRAMES',model:'old',assessedAt:'2026-10-01T12:00:00Z',acceptedAt:'2026-10-01T12:00:00Z',basis,profile};
assert.ok(readMechanics(envelope));assert.equal(summarizeExerciseMechanics(envelope,basis)?.status,'ACCEPTED');
const visual=visualAssessmentSchemaForCatalog(muscles.filter(m=>m.visualAssessable).map(m=>m.id), muscles.filter(m=>m.visualAssessable&&!m.accountingSlug).map(m=>m.id));
assert.ok(visual.shape.regions.element.shape.muscleId.safeParse(soleus.id).success);
assert.ok(!visual.shape.priorities.element.shape.muscleId.safeParse(soleus.id).success,'No independent soleus volume budget from a visual priority');
assert.ok(visual.shape.priorities.element.shape.muscleId.safeParse(calves.id).success);
assert.ok(!visual.shape.regions.element.shape.muscleId.safeParse(muscles.find(m=>m.slug==='subscapularis')!.id).success);
assert.equal(muscleCatalogContext(muscles).find(m=>m.id===soleus.id)?.accountingMuscleId,calves.id);
const sql=readFileSync('prisma/migrations/20261016060000_shared_muscle_model/migration.sql','utf8');
assert.ok(!/DELETE FROM|UPDATE exercise|UPDATE workout|UPDATE mesocycle|DISABLE ROW LEVEL|CREATE POLICY|GRANT /i.test(sql));
for (const file of ['lib/server/mesocycles.ts','lib/server/programs.ts']) assert.ok(readFileSync(file,'utf8').includes('accountingSlug: null'));
console.log(`Shared model: ${muscles.length} references, exact aliases, bounded IDs, preserved profiles, group accounting and photo visibility passed.`);
