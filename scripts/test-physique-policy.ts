import assert from "node:assert/strict";
import { photoIntervalDays, suggestComparison, daySchema, readVisualAssessment, type PhysiqueSettings } from "../lib/physique/policy";
const settings:PhysiqueSettings={trainingLevel:"LATE_INTERMEDIATE_ADVANCED",gainWeeks:10,maintenanceWeeks:6,goal:"Classic proportions"};
assert.equal(photoIntervalDays("CUTTING",settings),14);
assert.equal(photoIntervalDays("GAINING",{...settings,trainingLevel:"BEGINNER_MID_INTERMEDIATE"}),28);
for(const weeks of [8,10,12] as const)assert.equal(photoIntervalDays("GAINING",{...settings,gainWeeks:weeks}),weeks*7);
assert.equal(photoIntervalDays("GAINING",{...settings,trainingLevel:"UNSPECIFIED"}),null);
assert.equal(photoIntervalDays("MAINTAINING",settings),42);
assert.equal(photoIntervalDays(null,settings),null);
assert.equal(daySchema.safeParse("2026-02-30").success,false);
assert.equal(daySchema.safeParse("2026-02-28").success,true);
const row=(id:string,date:string,view="FRONT")=>({id,takenOn:new Date(date),photos:[{view}]});
const current=row("current","2026-10-15");
const previous=[row("recent","2026-10-01"),row("older","2026-08-06"),row("future","2026-12-01"),row("wrong-view","2026-08-05","BACK")];
assert.equal(suggestComparison(current,previous,14)?.id,"recent");
assert.equal(suggestComparison(current,previous,70)?.id,"older");
assert.equal(suggestComparison(current,[previous[2],previous[3]],70),null);
assert.equal(readVisualAssessment({version:2}),null);
console.log("Phase/experience photo cadence, true capture dates, compatible earlier comparisons and invalid-date guards passed.");
